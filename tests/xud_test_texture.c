/*-----------------------------------------------------------------------------------------------
 * The texel arrays every "the texture is fine" check below is the same texture seen through a
 * different refusal. The 4x4 is the one whose chain is knowable by hand: four 2x2 blocks, each a
 * different colour, so every level above 0 has a value a test can state rather than recompute.
 *-----------------------------------------------------------------------------------------------*/

/* 4x4, four 2x2 blocks, each a different mix: top-left all 8s, top-right two red 8s and two zero
   texels, bottom-left two green 8s and two zero texels, bottom-right all blue 8s. Every mip-1 texe
   l is therefore a hand-checkable average and mip 2 is the average of those four.
*/
static const uint8_t xudTestTexels4x4[4u * 4u * XUD_TEXTURE_BYTES_PER_TEXEL] = { 8u, 8u, 8u, 255u, 8u, 8u, 8u, 255u, 8u, 0u, 0u, 255u, 0u,
    0u, 0u, 255u, 8u, 8u, 8u, 255u, 8u, 8u, 8u, 255u, 8u, 0u, 0u, 255u, 0u, 0u, 0u, 255u, 0u, 8u, 0u, 255u, 0u, 8u, 0u, 255u, 0u, 0u, 8u,
    255u, 0u, 0u, 8u, 255u, 0u, 0u, 0u, 255u, 0u, 0u, 0u, 255u, 0u, 0u, 8u, 255u, 0u, 0u, 8u, 255u };

/* The 2x2 the exact averages are stated against: (0,0,0) (20,0,0) (0,40,0) (0,0,60), all opaque,
   so mip 1 is exactly (5,10,15,255) with no rounding at all.
*/
static const uint8_t xudTestTexels2x2[2u * 2u * XUD_TEXTURE_BYTES_PER_TEXEL]
    = { 0u, 0u, 0u, 255u, 20u, 0u, 0u, 255u, 0u, 40u, 0u, 255u, 0u, 0u, 60u, 255u };

/* A 3x5 sheet, the non-power-of-two case: the chain's length comes from the LONGER axis and the s
   hort axis clamps to 1 before the long one does, which is what makes level 1 a 1x2 rather than a
   0x1. The array is opaque grey so the chain's SHAPE is what is being checked rather than its colo
   ur.
*/
static const uint8_t xudTestTexels3x5[3u * 5u * XUD_TEXTURE_BYTES_PER_TEXEL] = { 17u, 34u, 51u, 255u, 17u, 34u, 51u, 255u, 17u, 34u, 51u,
    255u, 17u, 34u, 51u, 255u, 17u, 34u, 51u, 255u, 17u, 34u, 51u, 255u, 17u, 34u, 51u, 255u, 17u, 34u, 51u, 255u, 17u, 34u, 51u, 255u, 17u,
    34u, 51u, 255u, 17u, 34u, 51u, 255u, 17u, 34u, 51u, 255u, 17u, 34u, 51u, 255u, 17u, 34u, 51u, 255u, 17u, 34u, 51u, 255u };

/*-----------------------------------------------------------------------------------------------
 * The pure half: the chain's arithmetic, the gate, the stamps, the guard, the write and the refus
 * als, against shells
 *-----------------------------------------------------------------------------------------------*/

static void xud_test_texture_pure(void) {
    XudTextureRecord laid;
    XudTextureRecord narrow;
    XudTextureRecord zeroed;
    XudTextureRecord other;
    VkImageCreateInfo imageInfo;
    VkImageViewCreateInfo viewInfo;
    VkSamplerCreateInfo samplerInfo;
    VkBufferCreateInfo stagingInfo;
    VkMemoryRequirements reportedReq;
    XudDeviceCaps caps;
    XudHandleTable* table = NULL;
    XudHandle textureHandle = { 0u, 0u, 0u };
    XudHandle materialHandle = { 0u, 0u, 0u };
    XudHandle foreign = { 0u, 0u, 0u };
    const XudTextureRecord* record = NULL;
    void* rawRecord = NULL;
    uint32_t levels = 0u;
    uint32_t askedLevels = 0u;
    uint32_t closed = 0u;
    uint32_t live = 0u;
    uint32_t w = 0u;
    uint32_t h = 0u;
    uint8_t* staging = NULL;
    size_t stagingBytes = 0u;
    size_t guardBytes = 0u;
    size_t index = 0u;
    size_t touched = 0u;

    memset(&laid, 0, sizeof(laid));
    memset(&narrow, 0, sizeof(narrow));
    memset(&zeroed, 0, sizeof(zeroed));
    memset(&other, 0, sizeof(other));
    memset(&caps, 0, sizeof(caps));
    memset(&stagingInfo, 0, sizeof(stagingInfo));
    memset(&reportedReq, 0, sizeof(reportedReq));

    XudTextureData sheet = {
        .width = 4u, .height = 4u, .rgba = xudTestTexels4x4, .filter = XUD_TEXTURE_FILTER_LINEAR, .addressMode = XUD_TEXTURE_ADDRESS_REPEAT
    };
    XudTextureData tiny = { .width = 2u,
        .height = 2u,
        .rgba = xudTestTexels2x2,
        .filter = XUD_TEXTURE_FILTER_NEAREST,
        .addressMode = XUD_TEXTURE_ADDRESS_CLAMP_TO_EDGE };
    XudTextureData tall = { .width = 3u,
        .height = 5u,
        .rgba = xudTestTexels3x5,
        .filter = XUD_TEXTURE_FILTER_LINEAR,
        .addressMode = XUD_TEXTURE_ADDRESS_MIRRORED_REPEAT };
    XudTextureData broken = sheet;

    /*--- the chain's length, and what each extent says about it --------------------*/

    xud_check(xud_texture_mip_levels(1u, 1u, &levels) == XUD_OK, "texture/levels-1x1", "a 1x1 extent answers");
    xud_check(
        levels == 1u, "texture/levels-1x1-one", "and one level is the whole chain there is, so a 1x1 texture has no smaller one to select");
    xud_texture_mip_levels(4u, 4u, &levels);
    xud_check(levels == 3u, "texture/levels-4x4", "a 4x4 extent has three levels: 4, 2, 1 per axis");
    xud_texture_mip_levels(8u, 8u, &levels);
    xud_check(levels == 4u, "texture/levels-8x8", "and an 8x8 has four, so the count is the log of the LONGER axis plus one");
    xud_texture_mip_levels(3u, 5u, &levels);
    xud_check(levels == 3u, "texture/levels-3x5", "and a 3x5 has three too, because the short axis never decides the length");
    xud_texture_mip_levels(64u, 16u, &levels);
    xud_check(levels == 7u, "texture/levels-64x16", "and a 64x16 has seven, so the extent's aspect is not what the count is built from");
    xud_texture_mip_levels(4096u, 4096u, &levels);
    xud_check(levels == 13u, "texture/levels-4096",
        "and the spec's guaranteed 8192-class extent needs thirteen, which is why the mip arrays are at least fourteen rows deep");
    xud_check(xud_texture_mip_levels(0u, 4u, &levels) == XUD_INVALID_ARG, "texture/levels-zero-extent",
        "an extent of zero has no chain - there is nothing to halve");
    xud_check(xud_texture_mip_levels(4u, 4u, NULL) == XUD_INVALID_ARG, "texture/levels-no-out",
        "and the out-count is the answer, so a rung that fills nothing is refused rather than answering OK");

    /*--- one level's extent, and the clamp that makes a non-power-of-two shape legal --*/

    xud_check(xud_texture_mip_extent(3u, 5u, 0u, 3u, &w, &h) == XUD_OK, "texture/extent-3x5-base", "level 0 of a 3x5 answers");
    xud_check((w == 3u) && (h == 5u), "texture/extent-3x5-base-values",
        "and level 0 is the extent itself, so the chain starts at the caller's array");
    xud_check(xud_texture_mip_extent(3u, 5u, 1u, 3u, &w, &h) == XUD_OK, "texture/extent-3x5-one", "level 1 answers");
    xud_check((w == 1u) && (h == 2u), "texture/extent-3x5-one-values",
        "and it is 1x2, so the short axis clamped to 1 while the long one halved - a halving that rounded to 0 would be an axis the "
        "driver's own layout does not have");
    xud_check(xud_texture_mip_extent(3u, 5u, 2u, 3u, &w, &h) == XUD_OK, "texture/extent-3x5-two", "level 2 answers");
    xud_check((w == 1u) && (h == 1u), "texture/extent-3x5-two-values", "and the last level is 1x1, so the chain always ends at one texel");
    xud_check(xud_texture_mip_extent(3u, 5u, 3u, 3u, &w, &h) == XUD_INVALID_ARG, "texture/extent-past-chain",
        "and level 3 of a three-level chain is refused, so the loop bounds and the array bounds cannot disagree about where the chain "
        "ends");
    xud_check(xud_texture_mip_extent(4u, 4u, 1u, 3u, NULL, &h) == XUD_INVALID_ARG, "texture/extent-no-out",
        "and a missing out-extent is refused");

    /*--- the argument check, and what each refusal means ---------------------------*/

    xud_check(xud_texture_check(NULL, &askedLevels) == XUD_INVALID_ARG, "texture/check-null", "no description is refused");
    xud_check(xud_texture_check(&sheet, NULL) == XUD_OK, "texture/check-no-out-count",
        "the out-count is optional, so the check still answers without writing");

    broken = sheet;
    broken.width = 0u;
    xud_check(xud_texture_check(&broken, &askedLevels) == XUD_INVALID_ARG, "texture/check-zero-width",
        "an extent axis of zero is refused, because an image of no texels is an image this rung must not create");
    broken = sheet;
    broken.width = XUD_TEXTURE_MAX_DIMENSION + 1u;
    xud_check(xud_texture_check(&broken, &askedLevels) == XUD_INVALID_ARG, "texture/check-past-dimension-bound",
        "one past this rung's own extent bound is refused here rather than at the block acquire, so the reason is stated before a slot is "
        "spent");
    broken = sheet;
    broken.rgba = NULL;
    xud_check(xud_texture_check(&broken, &askedLevels) == XUD_INVALID_ARG, "texture/check-no-texel-array",
        "a texture with no texels is NOT a texture with a default: unlike a mesh's optional attribute streams, the texel array is the one "
        "array a texture has and the only one with no neutral value that means draw this");
    broken = sheet;
    broken.filter = XUD_TEXTURE_FILTER_COUNT;
    xud_check(xud_texture_check(&broken, &askedLevels) == XUD_INVALID_ARG, "texture/check-filter-past-axis",
        "a filter token outside its axis is the caller's mistake, not a capability this device lacks");
    broken = sheet;
    broken.filter = XUD_TEXTURE_FILTER_NEAREST;
    broken.addressMode = XUD_TEXTURE_ADDRESS_COUNT;
    xud_check(xud_texture_check(&broken, &askedLevels) == XUD_INVALID_ARG, "texture/check-address-past-axis",
        "and the same is true of the wrap mode");
    broken = sheet;
    broken.width = XUD_TEXTURE_MAX_DIMENSION;
    broken.height = 256u;
    xud_check(xud_texture_check(&broken, &askedLevels) == XUD_INVALID_ARG, "texture/check-past-texel-bound",
        "a texel count past the bound is refused before a slot or a block is spent, because the chain would not fit one request the "
        "allocator's block ceiling can serve - and both axes stay at or below the extent bound, so this refusal is the texel bound's "
        "rather than the dimension one's");
    xud_check(xud_texture_check(&sheet, &askedLevels) == XUD_OK, "texture/check-ok", "the 4x4 sheet is fine");
    xud_check(askedLevels == 3u, "texture/check-levels-filled",
        "and the check fills the chain's length, so the check and the levels rung cannot answer two different chains");

    /*--- the staging's byte layout ---------------------------------------------------*/

    xud_check(xud_texture_layout(&sheet, &laid) == XUD_OK, "texture/layout-4x4", "the 4x4 is laid out");
    xud_check((laid.width == 4u) && (laid.height == 4u) && (laid.mipLevels == 3u), "texture/layout-4x4-shape",
        "the extent and the chain's length are the caller's and the derived one");
    xud_check((laid.mipRowPitch[0] == 16u) && (laid.mipRowPitch[1] == 8u) && (laid.mipRowPitch[2] == 4u), "texture/layout-4x4-pitches",
        "each level's row pitch is that level's own width times the texel width, so the pitch moves with the level rather than staying at "
        "mip 0's");
    xud_check((laid.mipSize[0] == 64u) && (laid.mipSize[1] == 16u) && (laid.mipSize[2] == 4u), "texture/layout-4x4-sizes",
        "each level's size is that pitch times that level's height, so the areas form the quarter-ratio series");
    xud_check((laid.mipOffset[0] == 0u) && (laid.mipOffset[1] == 64u) && (laid.mipOffset[2] == 80u), "texture/layout-4x4-offsets",
        "the levels run back to back, so the staging is one block of the chain's total and the write and the bind read the same numbers");
    xud_check(laid.stagingBytes == 84u, "texture/layout-4x4-total",
        "and the total is 64+16+4, which is the 4/3 of mip 0 the series bound states rather than a number that happens to match");
    xud_check((laid.mipOffset[1] == (laid.mipOffset[0] + laid.mipSize[0])) && (laid.mipOffset[2] == (laid.mipOffset[1] + laid.mipSize[1])),
        "texture/layout-offsets-are-cumulative",
        "and each offset is the previous one plus the previous size, which is the one rule that makes the chain have no gaps and no "
        "overlaps");
    xud_check((laid.mipOffset[3] == 0u) && (laid.mipSize[3] == 0u), "texture/layout-unused-rows-zero",
        "and the rows past this extent's chain stay zero, so a loop that walked the array rather than the chain would be a loop over zeros "
        "rather than a loop over the chain");

    xud_check(xud_texture_layout(&tall, &narrow) == XUD_OK, "texture/layout-3x5", "the 3x5 sheet is laid out too");
    xud_check((narrow.mipRowPitch[0] == 12u) && (narrow.mipSize[0] == 60u), "texture/layout-3x5-mip0",
        "its first level is 3 wide at 12 B a row and 5 rows deep, 60 B");
    xud_check((narrow.mipRowPitch[1] == 4u) && (narrow.mipSize[1] == 8u), "texture/layout-3x5-mip1",
        "and its second is 1 wide at 4 B a row and 2 rows deep, 8 B - the clamped axis is what makes that row exist at all");
    xud_check((narrow.mipOffset[1] == 60u) && (narrow.mipSize[2] == 4u) && (narrow.stagingBytes == 72u), "texture/layout-3x5-total",
        "and the chain's total is 72 B, so a non-power-of-two extent's chain is SHORTER than the 4/3 series bound rather than equal to it");

    xud_check(xud_texture_layout(NULL, &laid) == XUD_INVALID_ARG, "texture/layout-no-description",
        "no description is refused by the layout as well as by the check, so the two pure halves cannot disagree about what a texture is");
    xud_check(xud_texture_layout(&sheet, NULL) == XUD_INVALID_ARG, "texture/layout-no-record",
        "and a record with nowhere to be written is refused");
    broken = sheet;
    broken.width = 0u;
    xud_check(xud_texture_layout(&broken, &other) == XUD_INVALID_ARG, "texture/layout-refuses-a-bad-texture",
        "and a texture the check refuses is refused by the layout too");
    xud_check(other.stagingBytes == 0u, "texture/layout-error-writes-nothing",
        "and the refused layout wrote nothing, so a caller cannot read a half-laid-out record");

    /*--- the caps gate -------------------------------------------------------------*/

    caps.properties.properties.limits.maxImageDimension2D = 8192u;
    xud_check(xud_texture_caps_support(&caps, &sheet) == XUD_OK, "texture/caps-8192",
        "a device that answers the spec's guaranteed 8192 is a device this sheet can be created on");
    caps.properties.properties.limits.maxImageDimension2D = 2u;
    xud_check(xud_texture_caps_support(&caps, &sheet) == XUD_UNSUPPORTED, "texture/caps-below-extent",
        "a device whose bound is below the extent is refused rather than an image created the driver would reject");
    caps.properties.properties.limits.maxImageDimension2D = 4u;
    xud_check(xud_texture_caps_support(&caps, &sheet) == XUD_OK, "texture/caps-exactly-enough",
        "and a bound exactly equal to the extent is accepted, because the limit bounds the extent rather than bounding one less than it");
    caps.properties.properties.limits.maxImageDimension2D = 4u;
    xud_check(xud_texture_caps_support(&caps, &tall) == XUD_UNSUPPORTED, "texture/caps-other-axis",
        "and the SAME bound refuses a 3x5 sheet, so both axes are gated and not only the larger of the two");
    xud_check(xud_texture_caps_support(NULL, &sheet) == XUD_INVALID_ARG, "texture/caps-no-caps", "no caps is a bad argument");

    /*--- the three create-infos ----------------------------------------------------*/

    xud_check(xud_texture_fill_image_info(&sheet, &laid, &imageInfo) == XUD_OK, "texture/info-image", "the image's row is stamped");
    xud_check((imageInfo.imageType == VK_IMAGE_TYPE_2D) && (imageInfo.arrayLayers == 1u) && (imageInfo.samples == VK_SAMPLE_COUNT_1_BIT),
        "texture/info-image-shape",
        "a 2D image, one layer, one sample - an array layer and a multisample are decisions this rung does not have");
    xud_check((imageInfo.extent.width == 4u) && (imageInfo.extent.height == 4u) && (imageInfo.extent.depth == 1u),
        "texture/info-image-extent", "the extent is the caller's, and a 2D image's depth is one");
    xud_check((imageInfo.mipLevels == 3u) && (imageInfo.format == XUD_TEXTURE_FORMAT) && (imageInfo.tiling == XUD_TEXTURE_TILING),
        "texture/info-image-chain",
        "the chain's length is the derived one, and the format and the tiling are this rung's constants rather than a driver's preference");
    xud_check((imageInfo.usage == XUD_TEXTURE_USAGE) && (imageInfo.initialLayout == XUD_TEXTURE_INITIAL_LAYOUT), "texture/info-image-usage",
        "the one use is a shader sampling it and the one layout is the create-time one that says the bytes were host-written before the "
        "first read, which is the only one of the three the create accepts that matches what this rung does");
    xud_check((imageInfo.flags == 0u) && (imageInfo.pNext == NULL) && (imageInfo.sharingMode == VK_SHARING_MODE_EXCLUSIVE)
            && (imageInfo.queueFamilyIndexCount == 0u) && (imageInfo.pQueueFamilyIndices == NULL),
        "texture/info-image-exclusive",
        "exclusive sharing with no queue family list, which is the same form the swapchain's and the descriptor's create-infos state");
    xud_check(xud_texture_fill_image_info(&sheet, &zeroed, &imageInfo) == XUD_INVALID_ARG, "texture/info-image-unlaid-record",
        "and a record whose chain was never laid out is refused, so a stamp cannot invent a level count");

    laid.image = (VkImage)1u; /* the state after vkCreateImage wrote one, which is the only state the view's stamp accepts */
    xud_check(xud_texture_fill_view_info(&laid, &viewInfo) == XUD_OK, "texture/info-view", "the view's row is stamped");
    xud_check((viewInfo.image == laid.image) && (viewInfo.viewType == VK_IMAGE_VIEW_TYPE_2D) && (viewInfo.format == XUD_TEXTURE_FORMAT),
        "texture/info-view-matches-image",
        "the view names the image and repeats its type and format, because a view whose format differs is a view that reinterprets the "
        "texels");
    xud_check((viewInfo.components.r == VK_COMPONENT_SWIZZLE_IDENTITY) && (viewInfo.components.g == VK_COMPONENT_SWIZZLE_IDENTITY)
            && (viewInfo.components.b == VK_COMPONENT_SWIZZLE_IDENTITY) && (viewInfo.components.a == VK_COMPONENT_SWIZZLE_IDENTITY),
        "texture/info-view-identity", "every channel is identity, so the view is not a channel-swapping lens on the texture");
    xud_check((viewInfo.subresourceRange.aspectMask == VK_IMAGE_ASPECT_COLOR_BIT) && (viewInfo.subresourceRange.baseMipLevel == 0u)
            && (viewInfo.subresourceRange.levelCount == 3u),
        "texture/info-view-whole-chain",
        "the view exposes the whole chain from the first level, which is what makes every LOD the sampler can select have a level behind "
        "it");
    xud_check((viewInfo.subresourceRange.baseArrayLayer == 0u) && (viewInfo.subresourceRange.layerCount == 1u) && (viewInfo.flags == 0u)
            && (viewInfo.pNext == NULL),
        "texture/info-view-one-layer", "and one array layer, the same one the image was created with");
    xud_check(xud_texture_fill_view_info(&zeroed, &viewInfo) == XUD_INVALID_ARG, "texture/info-view-no-image",
        "and a record whose image is still VK_NULL_HANDLE is refused, so the stamp cannot name an image that was never created");

    xud_check(xud_texture_fill_sampler_info(&sheet, &samplerInfo) == XUD_OK, "texture/info-sampler", "the sampler's row is stamped");
    xud_check((samplerInfo.magFilter == XUD_TEXTURE_FILTER_LINEAR) && (samplerInfo.minFilter == XUD_TEXTURE_FILTER_LINEAR),
        "texture/info-sampler-filter",
        "the caller's token fills BOTH filter slots, because raylib's SetTextureFilter names one and Vulkan's sampler has two");
    xud_check((samplerInfo.addressModeU == XUD_TEXTURE_ADDRESS_REPEAT) && (samplerInfo.addressModeV == XUD_TEXTURE_ADDRESS_REPEAT)
            && (samplerInfo.addressModeW == XUD_TEXTURE_ADDRESS_MODE_MIP),
        "texture/info-sampler-address",
        "the caller's wrap mode on U and V, and the fixed clamp on the mip axis, which is the axis that has no beyond");
    xud_check(
        (samplerInfo.mipmapMode == XUD_TEXTURE_MIPMAP_MODE) && (samplerInfo.minLod == 0.0f) && (samplerInfo.maxLod == VK_LOD_CLAMP_NONE),
        "texture/info-sampler-lod",
        "the LOD is interpolated between levels and the range covers the whole chain, so the chain this rung generates is a chain the "
        "sampler can actually walk");
    xud_check((samplerInfo.mipLodBias == 0.0f) && (samplerInfo.anisotropyEnable == VK_FALSE)
            && (samplerInfo.maxAnisotropy == XUD_TEXTURE_ANISOTROPY_MAX),
        "texture/info-sampler-no-anisotropy",
        "no LOD bias and no anisotropy: anisotropic filtering is a device feature and asking for it here would be choosing a quality level "
        "this library has no knob for");
    xud_check((samplerInfo.compareEnable == VK_FALSE) && (samplerInfo.compareOp == XUD_TEXTURE_COMPARE_OP)
            && (samplerInfo.unnormalizedCoordinates == VK_FALSE),
        "texture/info-sampler-no-compare", "no comparison sampler and normalised coordinates, which is what a texcoord attribute carries");
    xud_check((samplerInfo.borderColor == XUD_TEXTURE_BORDER_COLOR) && (samplerInfo.flags == 0u) && (samplerInfo.pNext == NULL),
        "texture/info-sampler-border-unused", "a border colour the sampler never reads, because no address mode above is a BORDER one");
    broken = sheet;
    broken.filter = XUD_TEXTURE_FILTER_COUNT;
    xud_check(xud_texture_fill_sampler_info(&broken, &samplerInfo) == XUD_INVALID_ARG, "texture/info-sampler-bad-token",
        "and a token outside its axis is refused by the stamp as well as by the check, so the sampler cannot be stamped from a token "
        "nothing defines");
    /*--- the staging buffer's create-info and the guard that reads its requirement back ------*/

    xud_check(xud_texture_fill_staging_info(&stagingInfo, laid.stagingBytes) == XUD_OK, "texture/staging-info",
        "the staging buffer's row is stamped for the chain's total");
    xud_check((stagingInfo.size == laid.stagingBytes) && (stagingInfo.usage == XUD_TEXTURE_STAGING_USAGE)
            && (stagingInfo.sharingMode == VK_SHARING_MODE_EXCLUSIVE),
        "texture/staging-info-shape",
        "one buffer, the copy-source use alone, exclusive - an owned buffer is the only sharing mode this rung has, because the upload is "
        "this rung's own command buffer");
    xud_check(xud_texture_fill_staging_info(&stagingInfo, 0u) == XUD_UNSUPPORTED, "texture/staging-info-empty",
        "and a chain of no bytes is refused rather than a buffer of no size, which is the same zero-size rule the allocator states for a "
        "block");
    xud_check(xud_texture_fill_staging_info(NULL, laid.stagingBytes) == XUD_INVALID_ARG, "texture/staging-info-no-out",
        "and a create-info with nowhere to be written is refused");

    reportedReq.size = laid.stagingBytes;
    reportedReq.alignment = 4u;
    reportedReq.memoryTypeBits = 0xFFFFFFFFu;
    xud_check(xud_texture_verify_staging(&laid, &reportedReq, laid.stagingBytes) == XUD_OK, "texture/staging-requirement-fits",
        "a driver that answers a buffer at least as long as the chain is accepted");
    reportedReq.size = laid.stagingBytes - 4u;
    xud_check(xud_texture_verify_staging(&laid, &reportedReq, laid.stagingBytes) == XUD_UNSUPPORTED,
        "texture/staging-requirement-too-small",
        "and a driver whose buffer is one texel short of the chain is refused, because the write below would be a write past what the "
        "copies then read from");
    reportedReq.size = laid.stagingBytes + 4u;
    xud_check(xud_texture_verify_staging(&laid, &reportedReq, laid.stagingBytes) == XUD_OK, "texture/staging-requirement-bigger-is-fine",
        "a driver that pads the buffer is accepted, because the staging buffer is OURS and the extra bytes are bytes no copy reads - which "
        "is the half of the guard that says the image's interior is the only interior this rung refuses to know about");
    reportedReq.size = laid.stagingBytes;
    reportedReq.alignment = 0u;
    xud_check(xud_texture_verify_staging(&laid, &reportedReq, laid.stagingBytes) == XUD_UNSUPPORTED, "texture/staging-alignment-zero",
        "and a driver that answers no alignment is refused, because the acquire below would be an acquire at an alignment of zero");
    xud_check(xud_texture_verify_staging(&laid, NULL, laid.stagingBytes) == XUD_INVALID_ARG, "texture/staging-no-requirement",
        "and no requirement is a bad argument");

    /*--- the write, into a heap staging rather than into a mapping -------------------*/

    stagingBytes = (size_t)laid.stagingBytes;
    guardBytes = 64u;
    staging = malloc(stagingBytes + guardBytes);
    xud_check(staging != NULL, "texture/write-staging-allocated", "the write is handed a heap buffer instead of one vkMapMemory wrote");
    if (staging != NULL) {
        memset(staging, 0xAAu, stagingBytes + guardBytes);
        xud_check(
            xud_texture_write_mips(&laid, &sheet, staging, stagingBytes) == XUD_OK, "texture/write-ok", "the write fills the staging");
        xud_check(memcmp(staging, xudTestTexels4x4, sizeof(xudTestTexels4x4)) == 0, "texture/write-mip0-is-callers",
            "and mip 0 is the caller's array byte for byte at the offset the layout named");
        xud_check((staging[64u] == 8u) && (staging[65u] == 8u) && (staging[66u] == 8u) && (staging[67u] == 255u),
            "texture/write-mip1-topleft",
            "and mip 1's first texel is the average of the four 8s above it, so the chain was generated rather than left at zero");
        xud_check((staging[68u] == 4u) && (staging[69u] == 0u) && (staging[70u] == 0u) && (staging[71u] == 255u),
            "texture/write-mip1-topright",
            "and the next texel is (4,0,0): two red 8s and two zero texels average to 4 in red and to 0 elsewhere, so the box filter is a "
            "real 2x2 and not a copy of the block's first texel");
        xud_check((staging[72u] == 0u) && (staging[73u] == 4u) && (staging[74u] == 0u) && (staging[75u] == 255u),
            "texture/write-mip1-bottomleft",
            "and the third level-1 texel is (0,4,0): the green block's 8s average to 4 in green alone, so the channels are averaged "
            "independently rather than one channel copied");
        xud_check((staging[76u] == 0u) && (staging[77u] == 0u) && (staging[78u] == 8u) && (staging[79u] == 255u),
            "texture/write-mip1-bottomright",
            "and the last level-1 texel is (0,0,8), the one block whose four texels all agree, so a block that needs no averaging still "
            "goes through the filter");
        xud_check((staging[80u] == 3u) && (staging[81u] == 3u) && (staging[82u] == 4u) && (staging[83u] == 255u),
            "texture/write-mip2-final",
            "and mip 2 is (3,3,4), the average of the four level-1 texels rather than of the sixteen mip-0 ones, so the chain was "
            "generated from the level below it as it sits in the staging");

        touched = 0u;
        for (index = stagingBytes; index < (stagingBytes + guardBytes); index++) {
            if (staging[index] != 0xAAu) {
                touched = 1u;
            }
        }
        xud_check(touched == 0u, "texture/write-stayed-inside",
            "and nothing was written past the chain's total, which is the one thing a write into a mapping has to guarantee about the "
            "block it was given");

        memset(staging, 0xAAu, stagingBytes + guardBytes);
        xud_check(xud_texture_write_mips(&laid, &tiny, staging, stagingBytes) == XUD_INVALID_ARG, "texture/write-extents-disagree",
            "and a record laid out for a 4x4 used to write a 2x2 array is refused, because the write sizes its loops from the record and "
            "reads its array from the description - the two have to name one texture");
        xud_check(xud_texture_write_mips(&laid, &sheet, NULL, stagingBytes) == XUD_INVALID_ARG, "texture/write-no-staging",
            "an staging with nowhere to be written is refused, so the write cannot be a write into nothing that answers OK");
        xud_check(xud_texture_write_mips(&laid, &sheet, staging, stagingBytes - 1u) == XUD_INVALID_ARG,
            "texture/write-destination-too-small",
            "and a destination one byte short of the layout's own total is refused rather than writing past it");
        zeroed.width = 4u;
        zeroed.height = 4u;
        xud_check(xud_texture_write_mips(&zeroed, &sheet, staging, stagingBytes) == XUD_UNSUPPORTED, "texture/write-unlaid-record",
            "and a record whose staging was never laid out is refused rather than writing every level at the same offset - the extents "
            "match here, so the refusal is the layout's and not the disagreement's");

        memset(staging, 0u, stagingBytes + guardBytes);
        xud_check(xud_texture_write_mips(&narrow, &tall, staging, (size_t)narrow.stagingBytes) == XUD_OK, "texture/write-3x5-ok",
            "the 3x5 sheet's chain is written");
        xud_check(memcmp(staging, xudTestTexels3x5, sizeof(xudTestTexels3x5)) == 0, "texture/write-3x5-mip0",
            "and its mip 0 is the caller's 60 B");
        xud_check((staging[60u] == 17u) && (staging[61u] == 34u) && (staging[62u] == 51u) && (staging[63u] == 255u),
            "texture/write-3x5-mip1-first",
            "and its level 1's first texel is the sheet's own grey, so the clamped row was repeated rather than read past the level below");
        xud_check((staging[64u] == 17u) && (staging[65u] == 34u) && (staging[66u] == 51u) && (staging[67u] == 255u),
            "texture/write-3x5-mip1-second",
            "and its second texel is the same grey, so a 3x5's level 1 really is 1x2 and the odd row was clamped rather than dropped");
        xud_check((staging[68u] == 17u) && (staging[69u] == 34u) && (staging[70u] == 51u) && (staging[71u] == 255u),
            "texture/write-3x5-mip2",
            "and its last level is one texel of the same grey at the offset the layout named, so the chain ends where the total says it "
            "ends");

        free(staging);
    }

    /*--- the slot, the accessor and the cross-kind refusal ---------------------------*/

    xud_check(xud_handle_table_open(&table) == XUD_OK, "texture/table-opened", "a table with no TEXTURE array yet is opened");
    xud_check(xud_texture_get(table, textureHandle, &record) == XUD_INVALID_ARG, "texture/get-no-array",
        "a kind whose array was never allocated names nothing, so the accessor refuses rather than reading a NULL array");

    xud_check(xud_handle_alloc(&textureHandle, table, XUD_HANDLE_KIND_TEXTURE) == XUD_OK, "texture/slot-allocated",
        "a TEXTURE slot is taken - the slot half of this rung's own bring-up, which is host-side and so runs with no driver present");
    xud_check(textureHandle.kind == XUD_HANDLE_KIND_TEXTURE, "texture/slot-kind", "and the handle names the TEXTURE kind");
    xud_check(xud_handle_record_get(table, XUD_HANDLE_KIND_TEXTURE, textureHandle.index, &rawRecord) == XUD_OK,
        "texture/slot-record-sentinel",
        "and the slot's record field is still the sentinel, because the record is the driver half's allocation and nothing above has run");
    xud_check(xud_texture_get(table, textureHandle, &record) == XUD_INVALID_ARG, "texture/get-sentinel-record",
        "and the accessor refuses a live slot whose record is the sentinel rather than handing back a NULL record every caller reads");

    xud_check(xud_handle_alloc(&materialHandle, table, XUD_HANDLE_KIND_MATERIAL) == XUD_OK, "texture/foreign-slot",
        "a MATERIAL slot in the SAME table, so the two handles share an index space and only the tag separates them");
    xud_check(xud_texture_get(table, materialHandle, &record) == XUD_INVALID_ARG, "texture/get-cross-kind",
        "and a handle of another kind is refused, which is the tag check the handle layer's own assertion states and the reason the public "
        "call validates rather than trusting the index");
    foreign = textureHandle;
    foreign.generation = 1u;
    xud_check(xud_texture_get(table, foreign, &record) == XUD_INVALID_ARG, "texture/get-stale",
        "and a handle kept across the release that freed the slot it names is refused by the generation bump rather than the index");

    xud_check(
        xud_handle_table_live_count(table, XUD_HANDLE_KIND_TEXTURE, &live) == XUD_OK, "texture/live-count-query", "the live count answers");
    xud_check(
        live == 1u, "texture/live-count-one", "and one TEXTURE slot is live, which is the handle layer's count rather than this rung's");

    /* A closed loader is the reason a driver half cannot run, and it is reported rather than a te
       xture being half-torn-down: the loader in hand here is a shell, so every driver half of this
       rung answers UNSUPPORTED before it touches the table.
    */
    xud_check(xud_texture_close(table, textureHandle, NULL, NULL, NULL) == XUD_INVALID_ARG, "texture/close-null-rungs",
        "a close with no loader, device or allocator is a bad argument");
    xud_check(xud_texture_close_all(table, NULL, NULL, NULL, &closed) == XUD_INVALID_ARG, "texture/close-all-null-rungs",
        "and the teardown rung refuses the same way");
    xud_check(xud_handle_record_get(table, XUD_HANDLE_KIND_TEXTURE, textureHandle.index, &rawRecord) == XUD_OK,
        "texture/close-refusal-left-the-record",
        "and a refused close freed nothing, so the slot still names what it named before - a refused release is a no-op rather than a "
        "half-release");
    xud_check(closed == 0u, "texture/close-all-refused-count",
        "and the out-count is zero on a refusal, so a caller cannot read a count of records that are still live");

    (void)xud_handle_table_close(&table);
}

/*-----------------------------------------------------------------------------------------------
 * The GPU half: the public pair against a real context
 *-----------------------------------------------------------------------------------------------*/

static void xud_test_texture_gpu(void) {
    XudContext* context = NULL;
    XudResult result = XUD_OK;
    XudHandle handle = { 0u, 0u, 0u };
    XudHandle second = { 0u, 0u, 0u };
    XudHandle material = { 0u, 0u, 0u };
    XudHandle foreign = { 0u, 0u, 0u };
    const XudTextureRecord* record = NULL;
    VkDeviceSize firstStagingBytes = 0u;
    uint32_t live = 0u;
    uint32_t closed = 0u;
    uint32_t y = 0u;
    uint32_t x = 0u;
    uint8_t texels8x8[8u * 8u * XUD_TEXTURE_BYTES_PER_TEXEL];

    /* The 8x8 the GPU half creates, filled by a fixed loop rather than spelled out: texel (x,y) i
       s (x*32, y*32, (x+y)*16, 255), so the sheet is a gradient a driver can be asked about withou
       t a colour being the point of any check below.
    */
    for (y = 0u; y < 8u; y++) {
        for (x = 0u; x < 8u; x++) {
            const uint32_t at = ((y * 8u) + x) * XUD_TEXTURE_BYTES_PER_TEXEL;
            texels8x8[at] = (uint8_t)(x * 32u);
            texels8x8[at + 1u] = (uint8_t)(y * 32u);
            texels8x8[at + 2u] = (uint8_t)((x + y) * 16u);
            texels8x8[at + 3u] = 255u;
        }
    }

    result = xud_init_context(&context, 64u, 64u);
    xud_check(result == XUD_OK, "gpu-texture/bringup-completes",
        "this machine has a Vulkan loader and a window system, so the ladder must complete");
    if (context == NULL) {
        return;
    }

    xud_check(context->handleTable != NULL, "gpu-texture/table-owned",
        "a context that completed owns the handle table the TEXTURE kind's row lives in");
    xud_check(xud_handle_table_live_count(context->handleTable, XUD_HANDLE_KIND_TEXTURE, &live) == XUD_OK, "gpu-texture/live-at-open-query",
        "the live count answers");
    xud_check(
        live == 0u, "gpu-texture/live-at-open", "and is zero, so a fresh context has no texture and no slot of the kind has been taken");

    /* The refusals against a real context, before any block is spent. */
    xud_check(
        xud_create_texture(NULL, context, &(XudTextureData) { .width = 4u, .height = 4u, .rgba = xudTestTexels4x4 }) == XUD_INVALID_ARG,
        "gpu-texture/create-null-out", "a handle with nowhere to be written is refused");
    xud_check(xud_create_texture(&handle, context, NULL) == XUD_INVALID_ARG, "gpu-texture/create-null-data", "no description is refused");
    xud_check(
        xud_create_texture(&handle, context, &(XudTextureData) { .width = 0u, .height = 4u, .rgba = xudTestTexels4x4 }) == XUD_INVALID_ARG,
        "gpu-texture/create-zero-extent", "and an extent axis of zero is refused BEFORE a slot or a block is spent");
    xud_check(xud_create_texture(&handle, context, &(XudTextureData) { .width = 4u, .height = 4u, .rgba = NULL }) == XUD_INVALID_ARG,
        "gpu-texture/create-no-texels",
        "and a texture with no texel array is refused, which is the one array a texture has and the one with no default");
    xud_check(xud_create_texture(&handle, context,
                  &(XudTextureData) { .width = 4u, .height = 4u, .rgba = xudTestTexels4x4, .filter = XUD_TEXTURE_FILTER_COUNT })
            == XUD_INVALID_ARG,
        "gpu-texture/create-bad-filter", "and a filter token outside its axis is refused before the same spend");
    xud_check(xud_handle_table_live_count(context->handleTable, XUD_HANDLE_KIND_TEXTURE, &live) == XUD_OK,
        "gpu-texture/live-after-refusals-query", "the live count answers again");
    xud_check(live == 0u, "gpu-texture/live-after-refusals", "and is still zero, so every refusal above left no half-texture behind");

    xud_check(xud_create_texture(&handle, context,
                  &(XudTextureData) { .width = 8u,
                      .height = 8u,
                      .rgba = texels8x8,
                      .filter = XUD_TEXTURE_FILTER_LINEAR,
                      .addressMode = XUD_TEXTURE_ADDRESS_REPEAT })
            == XUD_OK,
        "gpu-texture/create-ok",
        "an 8x8 texture is created against a real device - the array it is handed is mip 0's, and the chain above it is this library's "
        "work");
    xud_check(handle.kind == XUD_HANDLE_KIND_TEXTURE, "gpu-texture/create-kind",
        "and the handle names the TEXTURE kind, which is what makes a cross-kind close a caught runtime error rather than a layout "
        "coincidence");
    xud_check(xud_texture_get(context->handleTable, handle, &record) == XUD_OK, "gpu-texture/get-ok",
        "the record reads back through the accessor");
    xud_check((record != NULL) && (record->width == 8u) && (record->height == 8u) && (record->mipLevels == 4u), "gpu-texture/record-shape",
        "and the extent is the caller's while the chain's length is the derived one, so the record says what was created rather than what "
        "was asked for");
    xud_check((record->mipSize[0] == 256u) && (record->mipSize[1] == 64u) && (record->mipSize[2] == 16u) && (record->mipSize[3] == 4u),
        "gpu-texture/record-sizes",
        "and every level's size is that level's own extent times the texel width, so the chain is the quarter-ratio series rather than "
        "four copies of mip 0");
    xud_check(record->stagingBytes == 340u, "gpu-texture/record-total",
        "and the chain's total is 340 B, which is the number the staging buffer below was sized from - the driver's own requirement for "
        "that buffer, compared against this rung's layout rather than assumed equal");
    xud_check((record->image != VK_NULL_HANDLE) && (record->view != VK_NULL_HANDLE) && (record->sampler != VK_NULL_HANDLE),
        "gpu-texture/objects-created",
        "and the image, the view and the sampler are real Vulkan objects, so a texture created today owns the driver objects a material's "
        "record does not");
    xud_check(record->imageRange.memory != VK_NULL_HANDLE, "gpu-texture/image-memory",
        "and the image's block is a real VkDeviceMemory - the SUBALLOCATING acquire rather than the host-visible one, because the image is "
        "never mapped and the staging block above is the only mapping this rung takes");
    xud_check(record->imageBindOffset == record->imageRange.offset, "gpu-texture/bind-at-block-base",
        "the image is bound at the block's own base rather than at zero, which is what makes a block that does not start at zero still a "
        "block whose bytes are addressed correctly");
    xud_check(record->imageLayout == XUD_TEXTURE_SAMPLED_LAYOUT, "gpu-texture/image-layout",
        "and the record says the image ended in the sampled layout rather than the upload one, which is what makes the descriptor step's "
        "layout a fact read off the record rather than a guess about what the upload left behind");
    xud_check(
        (record->stagingBuffer == VK_NULL_HANDLE) && (record->stagingRange.memory == VK_NULL_HANDLE) && (record->stagingMappedLive == 0u),
        "gpu-texture/staging-retired",
        "and the staging half is empty in a live record, because the bytes the upload read are already inside the image - a record that "
        "kept them would be a record holding a second copy of every texture on the host");
    xud_check(record->imageInfo.mipLevels == record->mipLevels, "gpu-texture/stamp-agrees-with-record",
        "and the create-info the driver was handed agrees with the record about the chain, so the record and what was created cannot "
        "disagree");
    xud_check(record->viewInfo.subresourceRange.levelCount == record->mipLevels, "gpu-texture/view-exposes-chain",
        "and the view the driver was handed exposes the whole chain, so every LOD the sampler can select has a level behind it");
    xud_check(record->samplerInfo.mipmapMode == XUD_TEXTURE_MIPMAP_MODE, "gpu-texture/sampler-walks-chain",
        "and the sampler the driver was handed interpolates between levels, so the chain this rung generated is a chain the sampler can "
        "walk");
    xud_check(xud_handle_table_live_count(context->handleTable, XUD_HANDLE_KIND_TEXTURE, &live) == XUD_OK, "gpu-texture/live-after-query",
        "the live count answers");
    xud_check(live == 1u, "gpu-texture/live-after", "and moved to one");

    firstStagingBytes = (record != NULL) ? record->stagingBytes : 0u;

    xud_check(xud_create_texture(&second, context,
                  &(XudTextureData) { .width = 3u,
                      .height = 5u,
                      .rgba = xudTestTexels3x5,
                      .filter = XUD_TEXTURE_FILTER_NEAREST,
                      .addressMode = XUD_TEXTURE_ADDRESS_CLAMP_TO_EDGE })
            == XUD_OK,
        "gpu-texture/create-second-ok", "a 3x5 sheet is created beside it, so the non-power-of-two chain runs against a real device too");
    xud_check(second.index == handle.index + 1u, "gpu-texture/second-index",
        "and the index moved, so the two textures are two records and not one record restated");
    xud_check(
        xud_texture_get(context->handleTable, second, &record) == XUD_OK, "gpu-texture/second-get-ok", "the second record reads back");
    xud_check((record != NULL) && (record->mipLevels == 3u) && (record->mipRowPitch[1] == 4u) && (record->mipSize[1] == 8u),
        "gpu-texture/second-clamped-chain",
        "and its second level is 1 wide at 4 B a row and 2 rows deep, so the clamped axis is what the driver's own layout was asked for "
        "and what this rung wrote into");
    xud_check(record->stagingBytes < firstStagingBytes, "gpu-texture/second-smaller",
        "and its staging is smaller than the 8x8's, so the block is sized from the chain rather than from a fixed sheet size");
    xud_check(xud_handle_table_live_count(context->handleTable, XUD_HANDLE_KIND_TEXTURE, &live) == XUD_OK, "gpu-texture/live-two-query",
        "the live count answers");
    xud_check(live == 2u, "gpu-texture/live-two", "and two TEXTURE slots are live");

    /* The cross-kind close, refused before anything is destroyed. */
    xud_check(xud_create_material(&material, context, (XudMaterial) { .blendMode = XUD_BLEND_OPAQUE }) == XUD_OK,
        "gpu-texture/material-created", "a MATERIAL slot in the same table");
    xud_check(xud_close_texture(context, material) == XUD_INVALID_ARG, "gpu-texture/close-cross-kind",
        "and closing it as a texture is refused, so a handle of another kind cannot destroy a record of that other kind");
    foreign = handle;
    foreign.generation = handle.generation + 1u;
    xud_check(xud_close_texture(context, foreign) == XUD_INVALID_ARG, "gpu-texture/close-stale",
        "and a handle kept across the close of the texture it names is refused by the generation bump");
    xud_check(xud_handle_table_live_count(context->handleTable, XUD_HANDLE_KIND_TEXTURE, &live) == XUD_OK,
        "gpu-texture/live-still-two-query", "the live count answers");
    xud_check(live == 2u, "gpu-texture/live-still-two",
        "and both refusals destroyed nothing, so a refused release is a no-op rather than a half-release");

    xud_check(xud_close_texture(context, handle) == XUD_OK, "gpu-texture/close-ok", "the first texture is released");
    xud_check(xud_texture_get(context->handleTable, handle, &record) == XUD_INVALID_ARG, "gpu-texture/close-freed-the-slot",
        "and the handle no longer names a live slot, so a texture kept past its close is refused rather than dangling");
    xud_check(xud_handle_table_live_count(context->handleTable, XUD_HANDLE_KIND_TEXTURE, &live) == XUD_OK,
        "gpu-texture/live-after-close-query", "the live count answers");
    xud_check(live == 1u, "gpu-texture/live-after-close", "and one TEXTURE slot is live, the second texture still in hand");

    /* The teardown rung above the handle table's own close, run by xud_close_context(): the second
       texture is still live in a slot at this point, so the rung has one record to destroy and the
       allocator's close afterwards has one block to free.
    */
    xud_check(xud_texture_close_all(context->handleTable, context->loader, context->device, context->allocator, &closed) == XUD_OK,
        "gpu-texture/close-all-explicit", "the rung runs and closes the one TEXTURE record a slot still names");
    xud_check(closed == 1u, "gpu-texture/close-all-count", "and the count it reports is the one record that was still reachable");
    xud_check(xud_texture_close_all(context->handleTable, context->loader, context->device, context->allocator, &live) == XUD_OK,
        "gpu-texture/close-all-idempotent",
        "and running it again closes nothing, because every record pointer was cleared by the run above - the rung is idempotent rather "
        "than a double destroy");
    xud_check(live == 0u, "gpu-texture/close-all-second-count", "and the second count is zero");

    result = xud_close_context(&context);
    xud_check((result == XUD_OK) || (result == XUD_ALREADY), "gpu-texture/close-context",
        "the context closes with the texture rung's teardown inside it");
    xud_check(
        context == NULL, "gpu-texture/context-cleared", "and the context pointer is cleared, so a close run twice cannot double-free");
}


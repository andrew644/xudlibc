/***********************************************************************************************
 *
 *   xud_test_texture.c - the texture rung and the public texture API above it
 *
 *   Owns : the texture's own arithmetic (the chain's length for one extent, one level's extent,
 *          the staging's byte layout), its argument check, its caps gate, the three create-infos it
 *          stamps, the guard that reads the staging buffer's requirement back against the chain's total, the
 *          t fills the chain, the record a TEXTURE-kind slot carries, and the public pair xud_cre
 *          ate_texture()/xud_close_texture() - and nothing else: the handle layer's own validatio
 *          n order is the handle area's, the allocator's block discipline is the allocator area's
 *          , the image limits are the physical area's, and the teardown rung xud_close_context()
 *          runs above the handle table it closes is the core area's.
 *
 *   Layer: tests, above the mesh area and below the core area. The pure half runs with no driver
 *   present at all - a texture's staging is a range of bytes, so the write is handed a heap buffer i
 *   nstead of one vkMapMemory wrote, and the chain's length, one level's extent, the offsets, the g
 *   uard's comparison and the generated bytes are all answerable with no device in sight. The GPU h
 *   alf runs the same public pair against a real context, which is where the block, the bind, the m
 *   apping and the three Vulkan objects are observable at all.
 *
 *   What the checks are stated against: the offsets, sizes and pitches rather than the bytes at the
 *   m for the layout, the bytes at the offsets for the mip-0 copy, and the GENERATED values of a lev
 *   el whose average is knowable by hand for the chain - so the three halves are three different ki
 *   nds of fact rather than one set of numbers copied twice. The GPU half observes the live driver s
 *   tate (a non-null staging memory, a non-null mapping, a non-null image, view and sampler, and the d
 *   river's own chain total for an extent this layer computed). The readback half closes the last gap
 *   that left: it draws a full-screen quad through a material that names a NEAREST sheet, copies the
 *   presented swapchain image into a host buffer and compares every pixel against the sheet's own
 *   texel through the swapchain format's sRGB encoding - the first check in this tree that sees a tex
 *   el where a pixel should be.
 *
 *   Deterministic: fixed extents, fixed texel arrays, fixed loop counts, no time, no randomness, no
 *   filesystem.
 *
 *   Copyright (c) 2026 xudlibc authors.
 ***********************************************************************************************/

